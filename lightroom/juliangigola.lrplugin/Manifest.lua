--[[
  What an export does to content/projects.json, and nothing else.

  No Lightroom calls in here, so it can be tested outside Lightroom (see
  test.py beside this file). The rules are /admin's, so the two can take
  turns on the same file:

    - photos added to an existing project extend its sequence in `frames`,
      as /admin's gallery editor does. That is the only way that works for
      the harvested projects, whose own frames live in lib/work-data.ts and
      are regenerated by every harvest;
    - a new project goes to the front of `projects`, as /admin's "Add a
      project" does, and to the front of `order`, so a shoot uploaded today
      leads the running order instead of landing behind everything dragged.
]]

local Json = require "Json"

local M = {}

--- `Some Shoot Name` → `some-shoot-name`. Accents are dropped, not kept.
function M.slug(name)
  return (name:lower():gsub("[^a-z0-9]+", "-"):gsub("^%-+", ""):gsub("%-+$", ""))
end

--- An Instagram handle from whatever was typed; nil when nothing usable.
--  Same rule as instagramHandle() in lib/added.ts.
function M.handle(raw)
  local bare = raw:gsub("^%s+", ""):gsub("%s+$", ""):gsub("^@+", "")
    :gsub("^[Hh][Tt][Tt][Pp][Ss]?://[^/]*instagram%.com/", "")
    :gsub("[/?#].*$", ""):gsub("^@+", ""):lower()
  if #bare <= 30 and bare:match("^[a-z0-9_][a-z0-9._]*$") then return bare end
end

--- One credit per line: `Role: Name @handle`. The handle is optional.
function M.parseCredits(text)
  local out = Json.array()
  for line in (text or ""):gmatch("[^\r\n]+") do
    local role, rest = line:match("^%s*([^:]-)%s*:%s*(.-)%s*$")
    if role and role ~= "" and rest ~= "" then
      local name, at = rest:match("^(.-)%s+(%S+)$")
      if at and not (at:find("^@") or at:lower():find("instagram%.com/")) then name, at = nil, nil end
      local c = Json.object()
      Json.set(c, "role", role)
      Json.set(c, "name", name or rest)
      Json.set(c, "instagram", at and M.handle(at) or Json.null)
      out[#out + 1] = c
    end
  end
  return out
end

--- A frame, keys in the order /admin writes them.
function M.frame(src, width, height, color)
  local f = Json.object()
  Json.set(f, "src", src)
  Json.set(f, "width", width)
  Json.set(f, "height", height)
  Json.set(f, "color", color)
  Json.set(f, "alt", "")
  return f
end

--- Base 36, as /admin names uploads (`Date.now().toString(36)`).
function M.base36(n)
  local digits, out = "0123456789abcdefghijklmnopqrstuvwxyz", ""
  n = math.floor(n)
  repeat
    local d = n % 36
    out = digits:sub(d + 1, d + 1) .. out
    n = (n - d) / 36
  until n == 0
  return out
end

local function get(map, key)
  if type(map) == "table" and not Json.isArray(map) then return map[key] end
end

--- The harvested projects, out of lib/work-data.ts. The array is written
--  as JSON inside the TypeScript, so it decodes as JSON.
local function harvested(workData)
  local body = workData:match("export const PROJECTS: Project%[%] = (%b[])")
  return body and Json.decode(body) or {}
end

--- The site as /admin sees it: every live project, with the discipline,
--  name and gallery the build will give it.
--  Returns { disciplines = { {slug, name} ... }, projects = { {slug, name, discipline, hidden, gallery} ... } }
function M.site(doc, workData)
  local disciplines, known = {}, {}
  local block = workData:match("export const CATEGORIES: Category%[%] = (%b[])")
  for _, list in ipairs({ block and Json.decode(block) or {}, doc.disciplines or {} }) do
    for _, c in ipairs(list) do
      if not known[c.slug] then
        known[c.slug] = true
        disciplines[#disciplines + 1] = { slug = c.slug, name = c.name }
      end
    end
  end

  local hidden = {}
  for _, s in ipairs(doc.hidden or {}) do hidden[s] = true end

  local projects, seen = {}, {}
  local function add(p, discipline)
    local slug = get(doc.slugs, p.slug) or p.slug
    if seen[slug] then return end
    seen[slug] = true
    local paths = {}
    for i, f in ipairs(p.images or {}) do paths[i] = f.src end
    local copy = get(doc.copy, slug)
    projects[#projects + 1] = {
      slug = slug,
      name = copy and copy.title or p.name,
      discipline = get(doc.categories, slug) or discipline,
      hidden = hidden[slug] or false,
      images = paths,
    }
  end
  -- Added work first, as lib/work.ts merges them.
  for _, p in ipairs(doc.projects or {}) do add(p, p.categorySlug) end
  for _, p in ipairs(harvested(workData)) do add(p, p.categories[1] and p.categories[1].slug) end

  return { disciplines = disciplines, projects = projects, known = known }
end

function M.findProject(site, slug)
  for _, p in ipairs(site.projects) do
    if p.slug == slug then return p end
  end
end

--- Refuses a new project name that would collide with anything addressed
--  at /portfolio/<slug>: a project, a discipline, or a harvested slug.
function M.checkNew(site, workData, name, discipline)
  local slug = M.slug(name or "")
  if slug == "" then return nil, "Give the new project a name." end
  if M.findProject(site, slug) or site.known[slug]
    or workData:find('"slug": "' .. slug .. '"', 1, true) then
    return nil, ('"%s" is already taken on the site. Pick another name, or choose that project from the list.'):format(slug)
  end
  if not site.known[discipline] then return nil, ('"%s" is not a discipline on the site.'):format(tostring(discipline)) end
  return slug, nil
end

--- Adds a new project at the front. `cover` and `images` are frames.
function M.addProject(doc, fields)
  local p = Json.object()
  Json.set(p, "slug", fields.slug)
  Json.set(p, "name", fields.name)
  Json.set(p, "categorySlug", fields.categorySlug)
  Json.set(p, "credits", fields.credits)
  Json.set(p, "cover", fields.cover)
  Json.set(p, "images", Json.array(fields.images))
  table.insert(doc.projects, 1, p)

  if not Json.isArray(doc.order) then Json.set(doc, "order", Json.array()) end
  table.insert(doc.order, 1, fields.slug)
end

--- Extends a project's gallery with `frames`, at the end or the start.
--  The sequence starts from what the live build shows: the existing
--  `frames` override when there is one, else the project's own frames.
function M.addFrames(doc, project, frames, atStart)
  if type(doc.frames) ~= "table" or Json.isArray(doc.frames) then Json.set(doc, "frames", Json.object()) end
  local seq = doc.frames[project.slug]
  if not seq then
    seq = Json.array()
    for i, src in ipairs(project.images) do seq[i] = src end
  end
  for i, f in ipairs(frames) do
    if atStart then table.insert(seq, i, f) else seq[#seq + 1] = f end
  end
  Json.set(doc.frames, project.slug, seq)
end

function M.encode(doc) return Json.encode(doc) .. "\n" end

return M
